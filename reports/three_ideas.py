"""Writes delivery/CONTROL-GROUP.md and delivery/SEATBELT.md from the report JSONs.

    uv run python -m reports.three_ideas
(after reports.ab_replay, reports.crash_drill and reports.shadow_report)
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

FA = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")
OUT = Path("reports/out")


def fa(x) -> str:
    return str(x).translate(FA)


def pct(x) -> str:
    x = 0.0 if abs(x) < 0.0005 else x               # no "−0.000%"
    return "⁦" + fa(f"{x:+.3f}") + "٪⁩"


def load(name: str) -> dict | None:
    p = OUT / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def control_group() -> str:
    md = ["# گروه کنترل: Claude در برابر دوقلوی قاعده‌محور", "",
          "کنار موتور اصلی، یک **دوقلو** با همان موتور، همان دروازه‌ی ریسک و همان اجرا کار می‌کند؛ فقط به‌جای Claude یک قاعده‌ی ثابت "
          "(`manager/mock.py`) رژیم و سهم را تعیین می‌کند. دو مقایسه داریم:", "",
          "1. **بازپخش منصفانه** (`reports/ab_replay.py`): همان دقیقه‌های واقعی والکس دو بار از همان موتور و همان شبیه‌ساز اجرا "
          "می‌شود؛ یک بار با برنامه‌های واقعیِ ثبت‌شده‌ی Claude (در همان دقیقه‌ای که نوشته شدند) و یک بار با قاعده. هر تفاوتی کار مدیر است.",
          "2. **Claude دوقلو را می‌بیند**: از ظهر جمعه برنامه و موقعیت دوقلو در ورودی Claude است و Claude باید بنویسد کجا با آن موافق "
          "یا مخالف است و چرا (خط‌های `vs twin:` در `SELF-GRADING.md`).", ""]
    for tag, title in (("BTCTMN", "فقط BTCTMN (قانون واقعی حساب پراپ)"),
                       ("USDTTMN+BTCTMN", "هر دو بازار (آنچه برنامه‌های شب اول برایش نوشته شده بودند)")):
        d = load(f"ab-replay-{tag}.json")
        if not d:
            continue
        c, r = d["claude"], d["rules_twin"]
        md += [f"## {title}", "", f"بازه: {fa(d['from'][:16].replace('T', ' '))} تا {fa(d['to'][:16].replace('T', ' '))} تهران · "
               f"{fa(d['claude_playbooks'])} برنامه‌ی Claude", "",
               "| | بازده | بعد از فروش به تومان | بیشترین افت | معاملات | کارمزد (تومان) | سهم در پایان |", "|---|---|---|---|---|---|---|",
               f"| **Claude** | {pct(c['return_pct'])} | {pct(c['after_selling_to_tmn_pct'])} | {fa(c['max_drawdown_pct'])}٪ | "
               f"{fa(c['fills'])} | {fa(f'{c['fees_tmn']:,}')} | {fa(round(sum(c['exposure_end'].values()) * 100, 1))}٪ |",
               f"| دوقلوی قاعده‌محور | {pct(r['return_pct'])} | {pct(r['after_selling_to_tmn_pct'])} | {fa(r['max_drawdown_pct'])}٪ | "
               f"{fa(r['fills'])} | {fa(f'{r['fees_tmn']:,}')} | {fa(round(sum(r['exposure_end'].values()) * 100, 1))}٪ |",
               f"| ماندن در تومان | ۰٪ | ۰٪ | ۰٪ | ۰ | ۰ | ۰٪ |",
               f"| نگه‌داری ۱۰٪ بیت‌کوین از شروع | {pct(d['hold_btc_10pct']['return_pct'])} | — | — | ۲ | — | ۱۰٪ |", ""]
    md += ["**برداشت صادقانه:** در یک روز آرام و کمی صعودی، دوقلو با سهم بزرگ‌تر کمی بیشتر سود کاغذی گرفت؛ ولی مسابقه ارزش را بعد از "
           "فروش همه‌چیز به تومان می‌سنجد و فروش سهم بزرگ‌تر کارمزد بیشتری دارد. با قانون واقعی حساب (فقط BTCTMN)، نتیجه‌ی نهایی تقریباً "
           "مساوی است (اختلاف چند تومان)، در حالی که افت حساب Claude حدود یک‌هفتم و کارمزدش حدود یک‌هشتم دوقلوست. بیشتر این "
           "تفاوت از سهم کوچک‌تر Claude می‌آید (۴٪ در برابر ۱۵٪)؛ یعنی Claude با یک‌چهارم ریسک به همان نتیجه رسید، نه اینکه "
           "معامله‌ی بهتری پیدا کرده باشد. انتخاب همین سهم کوچک کار Claude بود، نه قاعده؛ و این همان چیزی است که Claude در "
           "برنامه‌هایش می‌گوید: «روز جمعه، کم‌حجم، چند ساعت تا پایان؛ ریسک کم بیشتر می‌ارزد». نمونه یک روز است و آن را ادعای برتری "
           "قطعی نمی‌دانیم؛ ارزش این بخش در خود سنجش است: هوش مصنوعی را با یک گروه کنترل واقعی مقایسه کرده‌ایم، نه با ادعا.", ""]
    return "\n".join(md) + "\n"


def seatbelt() -> str:
    d = load("crash-drill.json")
    md = ["# کمربند ایمنی: کدی که هوش مصنوعی نمی‌تواند دورش بزند", "",
          "Claude فقط «چه‌قدر و با چه رژیمی» را پیشنهاد می‌دهد. هر خرید و فروش از `engine/gate.py` می‌گذرد و تصمیم «مجاز / کوچک‌تر / رد» "
          "با نام قانون در لاگ ثبت می‌شود. حد ضرر، توقف روزانه، فروش اضطراری و فروش پایانی هم کد قطعی‌اند.", ""]
    if d:
        c, g = d["crash"], d["glitch"]
        md += ["## آزمون سقوط (`reports/crash_drill.py`)", "",
               f"همان موتور، روی دقیقه‌های واقعی والکس (۲۳ مهر از ساعت ۱۰ صبح) با یک شوک تزریقی ساعت ۱۲:", "",
               "| سناریو | سهم بیت‌کوین قبل از شوک | حرکت بیت‌کوین | با کمربند | بدون کمربند (نگه‌داری) |", "|---|---|---|---|---|",
               f"| سقوط ۱۰٪ در ۱۵ دقیقه | {fa(c['exposure_before_shock_pct'])}٪ | {pct(c['btc_move_pct'])} | **{pct(c['with_seatbelt_return_pct'])}** | {pct(c['held_through_return_pct'])} |",
               f"| یک قیمت خراب (−۳۰٪ برای یک دقیقه) | {fa(g['exposure_before_shock_pct'])}٪ | {pct(g['btc_move_pct'])} | **{pct(g['with_seatbelt_return_pct'])}** (هیچ فروشی) | {pct(g['held_through_return_pct'])} |", "",
               f"- در سقوط، حد ضرر هسته ساعت {fa(c['sells'][0]['t']) if c['sells'] else '—'} فعال شد و کل موقعیت را با سفارش محافظت‌شده فروخت؛ "
               "زیان حدود ۶۰٪ کمتر از نگه‌داری شد.",
               "- در قیمت خراب، محافظ «یک تیک خراب» (ملاک بالاتر از دو قیمت آخر) جلوی فروش وحشت‌زده را گرفت.",
               "- **این آزمون دو ایراد واقعی پیدا کرد** که همان روز درست و در نسخه‌ی زنده‌ی `live-v2` منتشر شد: (۱) بعد از فروش، باقیمانده‌ی "
               "چند تومانیِ کارمزد هر چند دقیقه دوباره «فروش» پیشنهاد می‌شد و دروازه ردش می‌کرد (لاگ پر از رد شدن)؛ حالا حد ضرر و فروش پایانی "
               "هر دارایی کمتر از حداقل سفارش والکس را نادیده می‌گیرند. صادقانه: مسیر «کاهش سهم» این اصلاح را نگرفت و در لاگ زنده هنوز هر چند دقیقه "
               "یک فروش ۵۰–۶۵ تومانی پیشنهاد می‌کند که دروازه با `G_BELOW_EXCHANGE_MIN` رد می‌کند؛ بی‌ضرر، ولی دیده می‌شود. (۲) قیمت خراب یک هشدار اشتباه «زیان روزانه ۱٪» می‌داد؛ حالا بررسی زیان روزانه هم "
               "همان محافظ قیمت خراب را دارد.", ""]
    rep = load("main-all-report.json") or load("main-report.json")
    if rep:
        b = rep["decisions"]["block_reasons"]
        md += ["## دخالت‌های واقعی دروازه (سایه + زنده)", "", "| قانون | دفعات |", "|---|---|"]
        md += [f"| `{k}` | {fa(v)} |" for k, v in Counter(b).most_common()]
        md += ["", "- `G_STALE_DATA`: بازار تتر بیش از ۱۱ ساعت معامله نداشت؛ دروازه خرید روی قیمت کهنه را رد کرد.",
               "- `G_MARKET_NOT_ALLOWED`: حساب پراپ فقط BTCTMN را می‌پذیرد؛ دروازه هر سفارش تتر را رد می‌کند."]
        if "G_BELOW_EXCHANGE_MIN" in b:
            md += ["- `G_BELOW_EXCHANGE_MIN` (با `G_DUST_CLOSE_ALL`/`G_SELL_CAPPED_TO_HELD`): پیشنهاد فروش خرده‌ی چند ده تومانیِ باقی‌مانده "
                   "از کارمزد، زیر حداقل سفارش والکس؛ دروازه رد می‌کند (بی‌ضرر)."]
        md += [""]
    md += ["## قوانین", "", "| قانون | مقدار |", "|---|---|",
           "| سقف هر بازار / کل | ۴۰٪ / ۶۰٪ |", "| هر افزایش | حداکثر ۱۰٪ سرمایه، دو بار در روز |",
           "| حد ضرر هر موقعیت | −۲٫۵٪ از میانگین خرید، بعد ۱۲ ساعت مکث |", "| زیان روزانه | −۱٪ → توقف خرید تا نیمه‌شب |",
           "| افت کل | −۲٪ → کل سهم حداکثر ۱۰٪ · −۳٪ → فروش همه و قفل |", "| بالشتک سود | از +۰٫۸٪ به بعد، ریسک تازه نمی‌تواند پایان را منفی کند |",
           "| کیفیت داده | قیمت کهنه، دفتر سفارش قفل‌شده، اسپرد بیش از ۳ برابر، یک قیمت خراب → خرید ممنوع / فروش وحشت‌زده ممنوع |",
           "| پول واقعی | دو قفل جدا؛ سفارش قناری قبل از شروع؛ تطبیق با موجودی والکس هر ۳۰ دقیقه |", ""]
    return "\n".join(md) + "\n"


def main():
    Path("delivery").mkdir(exist_ok=True)
    Path("delivery/CONTROL-GROUP.md").write_text(control_group(), encoding="utf-8")
    Path("delivery/SEATBELT.md").write_text(seatbelt(), encoding="utf-8")
    print("wrote delivery/CONTROL-GROUP.md and delivery/SEATBELT.md")


if __name__ == "__main__":
    main()
